/**
 * The per-category design tool.
 *
 * A brief is the single source for all three outputs (flat site, structured
 * data, 3D scaffold): it names one of the three layout archetypes in
 * layouts/, one of the nine themes in themes.js, the accent and hero
 * gradient, the CTA and WhatsApp opener, and the copy pack the layout
 * consumes.
 *
 * The copy pack is deliberately rich - headline, subhead, four value props,
 * services with descriptions, a "why us" grid, and an FAQ. That is what
 * fills the layouts without inventing facts about a specific business, and
 * it is where most of the visible difference between trades comes from.
 *
 * Fields:
 *   label          Hebrew name shown in the UI.
 *   searchPhrase   Hebrew plural used for the Places text search.
 *   schemaType     schema.org type for the JSON-LD block.
 *   layout         'showcase' | 'authority' | 'local' - picks the archetype.
 *   theme          key into STYLE_THEMES.
 *   accent/grad    hero accent + gradient the layout uses when there is no photo.
 *   cta/wa         button label and prefilled WhatsApp opener.
 *   copy           see above. Fallbacks only - real Places data always wins.
 *   three          preset key in three/presets.js for the 3D export.
 */

